_BY_NAME = {name: code for code, name in LANGUAGES.items()}
_BY_NAME.update(ALIASES)


def normalize_language(value):
    """Return whisper's language code for a hint, or None for auto-detect.

    Accepts a code ("es") or a language name ("Spanish"), case-insensitive.
    Missing, blank and "auto" all mean auto-detect. Raises ValueError for
    anything whisper would not accept.
    """
    if value is None:
        return None
    if not isinstance(value, str):
        raise ValueError("language must be a string")
    key = value.strip().lower()
    if key in ("", "auto"):
        return None
    if key in LANGUAGES:
        return key
    if key in _BY_NAME:
        return _BY_NAME[key]
    raise ValueError(f"unsupported language: {value!r}")
